import { build } from 'esbuild';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import path from 'node:path';
const root = path.resolve(import.meta.dirname, '..');
await mkdir(path.join(root, '.build'), { recursive: true });
const common = { bundle: true, minify: true, define: { 'process.env.NODE_ENV': '"production"' }, absWorkingDir: root };
await build({ ...common, entryPoints: ['src/story-server.jsx'], outfile: '.build/story-server.cjs', platform: 'node', format: 'cjs' });
const { default: { html } } = await import(pathToFileURL(path.join(root, '.build/story-server.cjs')).href);
const { outputFiles } = await build({ ...common, entryPoints: ['src/story-client.jsx'], outfile: 'story.js', platform: 'browser', format: 'esm', target: ['es2020'], write: false, legalComments: 'eof' });
const { createHash } = await import('node:crypto');
const js = outputFiles[0].contents;
const hash = createHash('sha256').update(js).digest('hex').slice(0, 12);
await writeFile(path.join(root, 'assets/story.js'), js);
const file = path.join(root, 'index.html');
const source = await readFile(file, 'utf8');
if (!source.includes('<!-- STORY:START -->') || !source.includes('<!-- STORY:END -->')) throw new Error('Story markers missing from index.html');
await writeFile(file, source.replace(/<!-- STORY:START -->[\s\S]*?<!-- STORY:END -->/, `<!-- STORY:START --><div id="artist-story">${html}</div><!-- STORY:END -->`)
  .replace(/src="assets\/story\.js(?:\?v=[^"]*)?"/, `src="assets/story.js?v=${hash}"`));
console.log('Narrativa pré-renderizada e bundle React gerados.');
